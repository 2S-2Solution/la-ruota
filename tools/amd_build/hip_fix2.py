#!/usr/bin/env python3
# VEGA: applica le sostituzioni CORE di hipify (mapping simboli + rename include) DIRETTAMENTE
# ai 3 sorgenti cuda, scrivendo gli output hip. Bypassa il matching all_files che li salta.
import os
import sys

sys.path.append(r"C:/LaRuota_workspace/pytorch_src/torch/utils")
from hipify import hipify_python as H  # type: ignore[import]

proj = r"C:/LaRuota_workspace/pytorch_src"
pairs = [
    ("aten/src/ATen/cuda/CUDAGeneratorImpl.h", "aten/src/ATen/hip/HIPGeneratorImpl.h"),
    ("aten/src/ATen/cuda/CUDAGeneratorImpl.cpp", "aten/src/ATen/hip/HIPGeneratorImpl.cpp"),
    ("aten/src/ATen/native/cuda/DistributionTemplates.h", "aten/src/ATen/native/hip/DistributionTemplates.h"),
]

# PYTORCH_MAP: costruiscilo dai mappings (come fa hipify per il trie)
PYTORCH_MAP = {}
for mapping in H.CUDA_TO_HIP_MAPPINGS:
    for src, value in mapping.items():
        # value e' una tupla (hip_name, meta_flags) nei mapping hipify
        try:
            hipname = value[0]
        except (TypeError, IndexError):
            hipname = value
        PYTORCH_MAP[src] = hipname


def hipify_text(text):
    text = H.RE_PYTORCH_PREPROCESSOR.sub(lambda m: PYTORCH_MAP.get(m.group(0), m.group(0)), text)

    _cuda_keys = ("cuda", "CUDA", "THC", "cudnn", "cublas", "curand", "cusparse", "cufft", "cusolver")

    def repl_angle(m):
        hdr = m.group(1)
        if any(k in hdr for k in _cuda_keys):
            return "#include <%s>" % H.get_hip_file_path(hdr, is_pytorch_extension=True)
        return m.group(0)

    def repl_quote(m):
        hdr = m.group(1)
        if any(k in hdr for k in _cuda_keys):
            return '#include "%s"' % H.get_hip_file_path(hdr, is_pytorch_extension=True)
        return m.group(0)

    text = H.RE_ANGLE_HEADER.sub(repl_angle, text)
    text = H.RE_QUOTE_HEADER.sub(repl_quote, text)
    return text


for cs, hd in pairs:
    with open(os.path.join(proj, cs), encoding="utf-8") as f:
        src = f.read()
    out = "// !!! This is a file automatically generated by hipify!!!\n" + hipify_text(src)
    dst = os.path.join(proj, hd)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as f:
        f.write(out)
    print("SCRITTO: " + hd)
print("=== HIP_FIX2 DONE ===")
